"""Certified unique-solution zebra puzzles as regenerable battery probes.

The module adopts five measurement patterns from Behnamian (2026), "Fair but
hard: certified unique-solution puzzles generated by language models":

1. Dual independent encoding: two independent encodings of the same probe
   text are accepted only when proven equivalent, because dual encoding
   catches every error made by one encoder and nothing two encoders share.
2. Certify the exact text the evaluator reads: the probe binds the SHA-256
   of the rendered text, not of an earlier draft of it.
3. One probe per call: batched evaluation changed measured accuracy more
   than puzzle difficulty did, so the battery wrapper refuses batches.
4. Honest null results: properties this module does not measure are
   reported UNKNOWN, never invented.
5. Every published number derives from saved results: the certificate
   carries the evidence for each claim it makes.

Scope of this first version is deliberately narrow: seeded generation of
minimal unique-solution zebra puzzles, uniqueness and minimality measured by
exhaustive search over the finite assignment space, and an equivalence
check for dual encodings.  The deduction ladder of the paper is NOT
MEASURED here and is reported UNKNOWN; difficulty claims are never made.

Standard library only; no randomness beyond the caller-supplied seed.
"""

from __future__ import annotations

import hashlib
import itertools
import random
from dataclasses import dataclass
from typing import Callable, Mapping, Sequence

PROBE_SCHEMA = "szl.frontier.certified-puzzle-probe.v1"
CALL_POLICY = "ONE_PROBE_PER_CALL"

Position = Mapping[str, int]
Expression = Callable[[Position], bool]


class PuzzleError(ValueError):
    """Raised when a puzzle specification or encoding is malformed."""


class BatchedCallError(RuntimeError):
    """Raised when a battery call carries other than exactly one probe."""


@dataclass(frozen=True, slots=True)
class ZebraSpec:
    """Categories whose values are placed one each on houses 1..houses."""

    categories: tuple[str, ...]
    values: Mapping[str, tuple[str, ...]]
    houses: int = 5

    def __post_init__(self) -> None:
        if not self.categories:
            raise PuzzleError("at least one category is required")
        if self.houses < 2:
            raise PuzzleError("houses must be >= 2")
        seen: set[str] = set()
        for category in self.categories:
            vals = tuple(self.values[category])
            if len(vals) != self.houses:
                raise PuzzleError(
                    f"category {category!r} needs exactly {self.houses} values"
                )
            for value in vals:
                if value in seen:
                    raise PuzzleError(f"duplicate value name: {value!r}")
                seen.add(value)
        object.__setattr__(self, "values", dict(self.values))

    def value_categories(self) -> dict[str, str]:
        return {
            value: category
            for category in self.categories
            for value in self.values[category]
        }


@dataclass(frozen=True, slots=True)
class Clue:
    """One clue: a formal expression, the values it reads, and its text."""

    expression: Expression
    values: tuple[str, ...]
    text: str

    def needed_categories(self, spec: ZebraSpec) -> frozenset[str]:
        cats = spec.value_categories()
        try:
            return frozenset(cats[value] for value in self.values)
        except KeyError as exc:
            raise PuzzleError(f"clue references unknown value: {exc.args[0]!r}") from None


def _check_reads_known_values(clue: Clue, spec: ZebraSpec) -> None:
    cats = spec.value_categories()
    for value in clue.values:
        if value not in cats:
            raise PuzzleError(f"clue references unknown value: {value!r}")


# ---------------------------------------------------------------------------
# Exhaustive search over the finite assignment space (the certificate engine)
# ---------------------------------------------------------------------------

def _category_order(spec: ZebraSpec, clues: Sequence[Clue]) -> list[str]:
    """Order categories by clue involvement so pruning starts early."""

    involvement = {category: 0 for category in spec.categories}
    cats = spec.value_categories()
    for clue in clues:
        for value in clue.values:
            involvement[cats[value]] += 1
    return sorted(spec.categories, key=lambda c: (-involvement[c], c))


def _iter_solutions(
    spec: ZebraSpec,
    clues: Sequence[Clue],
    *,
    limit: int,
    categories: Sequence[str] | None = None,
) -> list[dict[str, int]]:
    """Enumerate bijections satisfying every clue, up to limit, with pruning.

    Only the given categories are placed; expressions must read no values
    outside them.  Each placed category is a full permutation of its values
    over the houses, so the per-category all-different base constraint holds
    by construction, as in the paper.
    """

    order = list(categories) if categories is not None else _category_order(spec, clues)
    needed = [clue.needed_categories(spec) for clue in clues]
    positions = list(itertools.permutations(range(1, spec.houses + 1)))
    found: list[dict[str, int]] = []

    def recurse(level: int, position: dict[str, int], verified: frozenset[int]) -> None:
        if len(found) >= limit:
            return
        if level == len(order):
            found.append(dict(position))
            return
        category = order[level]
        placed = set(order[: level + 1])
        for permutation in positions:
            next_position = dict(position)
            for value, house in zip(spec.values[category], permutation):
                next_position[value] = house
            newly = [
                index
                for index in range(len(clues))
                if index not in verified and needed[index] <= placed
            ]
            if any(not clues[index].expression(next_position) for index in newly):
                continue
            recurse(level + 1, next_position, verified | frozenset(newly))

    recurse(0, {}, frozenset())
    return found


def count_solutions(spec: ZebraSpec, clues: Sequence[Clue], *, limit: int = 2) -> int:
    """Count satisfying bijections up to limit (cheap non-uniqueness proofs)."""

    return len(_iter_solutions(spec, clues, limit=limit))


def solution_of(spec: ZebraSpec, clues: Sequence[Clue]) -> dict[str, int] | None:
    """Return the unique solution, or None when the puzzle is not unique."""

    solutions = _iter_solutions(spec, clues, limit=2)
    return solutions[0] if len(solutions) == 1 else None


# ---------------------------------------------------------------------------
# Dual independent encoding: equivalence checked, never assumed
# ---------------------------------------------------------------------------

def encodings_equivalent(
    spec: ZebraSpec,
    encoding_a: Sequence[Clue],
    encoding_b: Sequence[Clue],
) -> tuple[bool, dict[str, int] | None]:
    """Prove two encodings of the same text equivalent, or return a witness.

    The encodings are equivalent when no bijection satisfies one while
    violating the other.  A satisfying witness is returned for diagnosis;
    dual encoding catches every single-encoder error but nothing two
    encoders share, so callers must still certify the text itself.
    """

    for clue in list(encoding_a) + list(encoding_b):
        _check_reads_known_values(clue, spec)
    mentioned: list[str] = []
    for clue in list(encoding_a) + list(encoding_b):
        for category in clue.needed_categories(spec):
            if category not in mentioned:
                mentioned.append(category)

    def witness(all_true: Sequence[Clue], violated: Sequence[Clue]) -> dict[str, int] | None:
        for violator in violated:
            def negated(position: Position) -> bool:
                return not violator.expression(position)

            negated_clue = Clue(
                expression=negated, values=violator.values, text=f"NOT({violator.text})"
            )
            hits = _iter_solutions(
                spec,
                list(all_true) + [negated_clue],
                limit=1,
                categories=mentioned,
            )
            if hits:
                return hits[0]
        return None

    from_b = witness(encoding_a, encoding_b)
    if from_b is not None:
        return False, from_b
    from_a = witness(encoding_b, encoding_a)
    if from_a is not None:
        return False, from_a
    return True, None

# ---------------------------------------------------------------------------
# Seeded generation: draw a solution, add true clues, certify, minimise
# ---------------------------------------------------------------------------

def _pool(spec: ZebraSpec, solution: Position) -> list[Clue]:
    """Every candidate clue of the typed relations, all true in the solution."""

    pool: list[Clue] = []
    names = [value for category in spec.categories for value in spec.values[category]]
    for house in range(1, spec.houses + 1):
        for name in names:
            if solution[name] == house:
                pool.append(
                    Clue(
                        expression=(lambda n, h: lambda p: p[n] == h)(name, house),
                        values=(name,),
                        text=f"The {name} is in house {house}.",
                    )
                )
            else:
                pool.append(
                    Clue(
                        expression=(lambda n, h: lambda p: p[n] != h)(name, house),
                        values=(name,),
                        text=f"The {name} is not in house {house}.",
                    )
                )
    for index, left in enumerate(names):
        for right in names[index + 1 :]:
            pair = (left, right)
            a, b = solution[left], solution[right]
            if a < b:
                low, high = left, right
            else:
                low, high = right, left
            same = a == b
            relations = [
                (same, f"The {left} and the {right} are the same person.",
                 (lambda x, y: lambda p: p[x] == p[y])(left, right)),
                (not same, f"The {left} and the {right} are different people.",
                 (lambda x, y: lambda p: p[x] != p[y])(left, right)),
                (abs(a - b) == 1 and a < b,
                 f"The {left} is directly to the left of the {right}.",
                 (lambda x, y: lambda p: p[x] + 1 == p[y])(left, right)),
                (abs(a - b) == 1 and a > b,
                 f"The {right} is directly to the left of the {left}.",
                 (lambda x, y: lambda p: p[y] + 1 == p[x])(left, right)),
                (abs(a - b) == 1, f"The {left} and the {right} are neighbours.",
                 (lambda x, y: lambda p: abs(p[x] - p[y]) == 1)(left, right)),
                (abs(a - b) != 1, f"The {left} and the {right} are not neighbours.",
                 (lambda x, y: lambda p: abs(p[x] - p[y]) != 1)(left, right)),
                (a < b, f"The {left} is somewhere to the left of the {right}.",
                 (lambda x, y: lambda p: p[x] < p[y])(left, right)),
                (abs(a - b) == 2, f"Exactly one house separates the {left} and the {right}.",
                 (lambda x, y: lambda p: abs(p[x] - p[y]) == 2)(left, right)),
                (a in (1, spec.houses), f"The {left} is in an end house.",
                 (lambda x, h: lambda p: p[x] in (1, h))(left, spec.houses)),
                (b in (1, spec.houses), f"The {right} is in an end house.",
                 (lambda x, h: lambda p: p[x] in (1, h))(right, spec.houses)),
            ]
            for holds, text, expression in relations:
                if holds:
                    pool.append(
                        Clue(expression=expression, values=(left, right), text=text)
                    )
    return pool


def generate_puzzle(spec: ZebraSpec, seed: int) -> "CertifiedPuzzle":
    """Generate a minimal unique-solution puzzle; every claim is measured."""

    rng = random.Random(seed)
    solution: dict[str, int] = {}
    for category in spec.categories:
        for value, house in zip(
            spec.values[category], rng.sample(range(1, spec.houses + 1), spec.houses)
        ):
            solution[value] = house
    pool = _pool(spec, solution)

    clues: list[Clue] = []
    while True:
        existing = _iter_solutions(spec, clues, limit=2)
        if len(existing) == 1:
            if existing[0] != solution:
                raise PuzzleError("unique solution diverged from the seeded one")
            break
        counterexample = existing[0] if existing[0] != solution else existing[1]
        blocking = [c for c in pool if not c.expression(counterexample)]
        if not blocking:
            raise PuzzleError("pool exhausted; cannot reach uniqueness")
        clues.append(rng.choice(blocking))

    # Minimise to a fixpoint: every removal that keeps uniqueness is taken.
    changed = True
    while changed:
        changed = False
        for index in rng.sample(range(len(clues)), len(clues)):
            trial = clues[:index] + clues[index + 1 :]
            if trial and count_solutions(spec, trial) == 1:
                clues = trial
                changed = True
                break

    # Measure minimality honestly instead of trusting the loop above.
    minimal = all(
        count_solutions(spec, clues[:index] + clues[index + 1 :]) != 1
        for index in range(len(clues))
    )
    return CertifiedPuzzle(spec, tuple(clues), solution, seed, minimal=minimal)

# ---------------------------------------------------------------------------
# The probe certificate and the one-probe-per-call policy
# ---------------------------------------------------------------------------

@dataclass(frozen=True, slots=True)
class CertifiedPuzzle:
    """A zebra puzzle with measured uniqueness and minimality."""

    spec: ZebraSpec
    clues: tuple[Clue, ...]
    solution: Mapping[str, int]
    seed: int
    minimal: bool

    @property
    def text(self) -> str:
        header = "Each clue below is true; exactly one assignment fits all of them.\n"
        return header + "\n".join(
            f"{index}. {clue.text}" for index, clue in enumerate(self.clues, start=1)
        )

    @property
    def text_sha256(self) -> str:
        return hashlib.sha256(self.text.encode("utf-8")).hexdigest()

    def certificate(self, *, dual_encodings: tuple[Sequence[Clue], ...] | None = None) -> dict:
        """Return the probe record; every verdict is measured or UNKNOWN."""

        unique = count_solutions(self.spec, self.clues) == 1
        record = {
            "schema": PROBE_SCHEMA,
            "seed": self.seed,
            "houses": self.spec.houses,
            "categories": list(self.spec.categories),
            "clueCount": len(self.clues),
            "clueTexts": [clue.text for clue in self.clues],
            "textSha256": self.text_sha256,
            "uniqueness": {"verdict": "MEASURED", "unique": unique},
            "minimality": {"verdict": "MEASURED", "minimal": self.minimal},
            "ladder": {"verdict": "UNKNOWN", "level": None},
            "callPolicy": CALL_POLICY,
            "encodingEquivalence": {"verdict": "UNKNOWN", "equivalent": None},
        }
        if dual_encodings is not None:
            if len(dual_encodings) != 2:
                raise PuzzleError("dual encoding means exactly two encodings")
            equivalent, witness = encodings_equivalent(
                self.spec, dual_encodings[0], dual_encodings[1]
            )
            record["encodingEquivalence"] = {
                "verdict": "MEASURED",
                "equivalent": equivalent,
                "witness": witness,
            }
        return record


def battery_call(*probes: object) -> object:
    """Return the single probe of a battery call; refuse every batch.

    Batching changed measured accuracy more than difficulty in the source
    study, so this policy is enforced structurally rather than by advice.
    """

    if len(probes) != 1:
        raise BatchedCallError(
            f"battery policy {CALL_POLICY}: got {len(probes)} probes, need 1"
        )
    return probes[0]
